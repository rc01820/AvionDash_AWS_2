#!/usr/bin/env bash
# Deploy AvionPulse to AWS (SAM stack + static site upload).
#
#   ./scripts/deploy.sh
#   DD_API_KEY=xxx BUDGET_EMAIL=me@example.com ./scripts/deploy.sh
#   DD_API_KEY=xxx RUM_APPLICATION_ID=xxx RUM_CLIENT_TOKEN=pubxxx ./scripts/deploy.sh
#
# Requires AWS CLI v2 and AWS SAM CLI with credentials for the target account.
set -euo pipefail
cd "$(dirname "$0")/.."

STACK_NAME="${STACK_NAME:-avionpulse}"
REGION="${AWS_REGION:-us-east-1}"
APP_ENV="${APP_ENV:-demo}"
DD_SITE="${DD_SITE:-datadoghq.com}"
DD_PY_LAYER="${DD_PY_LAYER:-107}"
DD_EXT_LAYER="${DD_EXT_LAYER:-80}"
RUM_APPLICATION_ID="${RUM_APPLICATION_ID:-}"
RUM_CLIENT_TOKEN="${RUM_CLIENT_TOKEN:-}"
BUDGET_EMAIL="${BUDGET_EMAIL:-}"
MONTHLY_BUDGET_USD="${MONTHLY_BUDGET_USD:-5}"

for tool in aws sam; do command -v "$tool" >/dev/null || { echo "$tool CLI not found" >&2; exit 1; }; done

SSM_NAME="/${STACK_NAME}/datadog/api-key"
ENABLE_DD=false
if [[ -n "${DD_API_KEY:-}" ]]; then
  echo "==> Storing Datadog API key in SSM ($SSM_NAME, SecureString, free standard tier)"
  aws ssm put-parameter --region "$REGION" --name "$SSM_NAME" --type SecureString --value "$DD_API_KEY" --overwrite >/dev/null
  ENABLE_DD=true
else
  echo "==> No DD_API_KEY: deploying without the Datadog layers"
fi

echo "==> sam deploy ($STACK_NAME in $REGION)"
sam deploy \
  --template-file template.yaml \
  --stack-name "$STACK_NAME" \
  --region "$REGION" \
  --resolve-s3 \
  --capabilities CAPABILITY_IAM CAPABILITY_AUTO_EXPAND \
  --no-confirm-changeset --no-fail-on-empty-changeset \
  --tags app=avionpulse suite=aviondash \
  --parameter-overrides \
    "AppEnv=$APP_ENV" "EnableDatadog=$ENABLE_DD" "DatadogSite=$DD_SITE" \
    "DatadogApiKeySsmName=$SSM_NAME" \
    "DatadogPythonLayerVersion=$DD_PY_LAYER" "DatadogExtensionLayerVersion=$DD_EXT_LAYER" \
    "BudgetEmail=$BUDGET_EMAIL" "MonthlyBudgetUsd=$MONTHLY_BUDGET_USD" \
    ${ADMIN_PASSWORD:+"AdminPassword=$ADMIN_PASSWORD"}

out() { aws cloudformation describe-stacks --region "$REGION" --stack-name "$STACK_NAME" \
          --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text; }
BUCKET=$(out BucketName); DIST_ID=$(out DistributionId); SITE_URL=$(out SiteUrl)

case "$DD_SITE" in
  datadoghq.eu) RUM_REGION=eu1 ;; us3.datadoghq.com) RUM_REGION=us3 ;;
  us5.datadoghq.com) RUM_REGION=us5 ;; ap1.datadoghq.com) RUM_REGION=ap1 ;; *) RUM_REGION=us1 ;;
esac

echo "==> Uploading web tier to s3://$BUCKET"
TMP_CONFIG=$(mktemp)
cat > "$TMP_CONFIG" <<EOF
// Generated by scripts/deploy.sh — do not edit by hand.
window.AVIONPULSE_CONFIG = {
  env: '$APP_ENV',
  version: '1.0.0',
  rum: {
    applicationId: '$RUM_APPLICATION_ID',
    clientToken: '$RUM_CLIENT_TOKEN',
    site: '$DD_SITE',
    scriptUrl: 'https://www.datadoghq-browser-agent.com/$RUM_REGION/v6/datadog-rum.js',
    replaySampleRate: 20,
  },
};
EOF
aws s3 sync web "s3://$BUCKET" --region "$REGION" --delete --exclude "static/js/config.js" >/dev/null
aws s3 cp "$TMP_CONFIG" "s3://$BUCKET/static/js/config.js" --region "$REGION" --content-type application/javascript >/dev/null
rm -f "$TMP_CONFIG"

echo "==> Invalidating CloudFront cache"
aws cloudfront create-invalidation --distribution-id "$DIST_ID" --paths "/*" >/dev/null

echo
echo "AvionPulse is live: $SITE_URL"
echo "Login: admin / aviondash123  (first CloudFront deploy can take a few minutes to propagate)"
