<#
.SYNOPSIS
  Deploy AvionPulse to AWS (SAM stack + static site upload).

.EXAMPLE
  ./scripts/deploy.ps1
  ./scripts/deploy.ps1 -Region us-east-1 -DatadogApiKey $env:DD_API_KEY -BudgetEmail me@example.com
  ./scripts/deploy.ps1 -DatadogApiKey $env:DD_API_KEY -RumApplicationId xxx -RumClientToken pubxxx

  Requires: AWS CLI v2 and AWS SAM CLI, with credentials for the target account.
#>
param(
  [string]$StackName = "avionpulse",
  [string]$Region = $(if ($env:AWS_REGION) { $env:AWS_REGION } else { "us-east-1" }),
  [string]$AppEnv = "demo",
  [string]$DatadogApiKey = $env:DD_API_KEY,
  [string]$DatadogSite = $(if ($env:DD_SITE) { $env:DD_SITE } else { "datadoghq.com" }),
  [int]$DatadogPythonLayerVersion = 107,
  [int]$DatadogExtensionLayerVersion = 80,
  [string]$RumApplicationId = "",
  [string]$RumClientToken = "",
  [string]$BudgetEmail = "",
  [string]$AdminPassword = "",
  [int]$MonthlyBudgetUsd = 5
)
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

foreach ($tool in "aws", "sam") {
  if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) { throw "$tool CLI not found on PATH" }
}

$ssmName = "/$StackName/datadog/api-key"
$enableDd = "false"
if ($DatadogApiKey) {
  Write-Host "==> Storing Datadog API key in SSM ($ssmName, SecureString, free standard tier)"
  aws ssm put-parameter --region $Region --name $ssmName --type SecureString --value $DatadogApiKey --overwrite | Out-Null
  $enableDd = "true"
} else {
  Write-Host "==> No Datadog API key given: deploying without the Datadog layers"
}

Write-Host "==> sam deploy ($StackName in $Region)"
sam deploy `
  --template-file template.yaml `
  --stack-name $StackName `
  --region $Region `
  --resolve-s3 `
  --capabilities CAPABILITY_IAM CAPABILITY_AUTO_EXPAND `
  --no-confirm-changeset --no-fail-on-empty-changeset `
  --tags app=avionpulse suite=aviondash `
  --parameter-overrides `
    "AppEnv=$AppEnv" "EnableDatadog=$enableDd" "DatadogSite=$DatadogSite" `
    "DatadogApiKeySsmName=$ssmName" `
    "DatadogPythonLayerVersion=$DatadogPythonLayerVersion" "DatadogExtensionLayerVersion=$DatadogExtensionLayerVersion" `
    "BudgetEmail=$BudgetEmail" "MonthlyBudgetUsd=$MonthlyBudgetUsd" `
    $(if ($AdminPassword) { "AdminPassword=$AdminPassword" })
if ($LASTEXITCODE -ne 0) { throw "sam deploy failed" }

$outputs = aws cloudformation describe-stacks --region $Region --stack-name $StackName `
  --query "Stacks[0].Outputs" --output json | ConvertFrom-Json
function Out-Value($key) { ($outputs | Where-Object OutputKey -eq $key).OutputValue }
$bucket = Out-Value "BucketName"
$distId = Out-Value "DistributionId"
$siteUrl = Out-Value "SiteUrl"

Write-Host "==> Uploading web tier to s3://$bucket"
$rumSite = $DatadogSite
$rumRegion = switch ($DatadogSite) { "datadoghq.eu" { "eu1" } "us3.datadoghq.com" { "us3" } "us5.datadoghq.com" { "us5" } "ap1.datadoghq.com" { "ap1" } default { "us1" } }
$configJs = @"
// Generated by scripts/deploy.ps1 — do not edit by hand.
window.AVIONPULSE_CONFIG = {
  env: '$AppEnv',
  version: '1.0.0',
  rum: {
    applicationId: '$RumApplicationId',
    clientToken: '$RumClientToken',
    site: '$rumSite',
    scriptUrl: 'https://www.datadoghq-browser-agent.com/$rumRegion/v6/datadog-rum.js',
    replaySampleRate: 20,
  },
};
"@
$tmpConfig = Join-Path ([IO.Path]::GetTempPath()) "avionpulse-config.js"
Set-Content -Path $tmpConfig -Value $configJs -Encoding utf8
aws s3 sync web "s3://$bucket" --region $Region --delete --exclude "static/js/config.js" | Out-Null
aws s3 cp $tmpConfig "s3://$bucket/static/js/config.js" --region $Region --content-type "application/javascript" | Out-Null
Remove-Item $tmpConfig

Write-Host "==> Invalidating CloudFront cache"
aws cloudfront create-invalidation --distribution-id $distId --paths "/*" | Out-Null

Write-Host ""
Write-Host "AvionPulse is live: $siteUrl"
Write-Host "Login: admin / aviondash123  (first CloudFront deploy can take a few minutes to propagate)"
